/**
 * ════════════════════════════════════════════════════════════════════
 * ⚧ الجنس: مفرداتٌ مغلقة في التطبيق، حرّة في القاعدة
 * ════════════════════════════════════════════════════════════════════
 *
 * القاعدة **تحرس** المفردات فعلاً: على الجداول الخمسة التي تحمل العمود
 * قيد `CHECK (gender = ANY (ARRAY['male', 'female']))`.
 *
 * لكنّ مولّد أنواع Supabase لا يقرأ قيود CHECK — الأنواع المُعدّدة وحدها
 * تُترجم إلى اتّحاد — فيبقى النوع المولَّد `string | null` رغم أنّ القيمة
 * مضمونة. هذه الدالّة تسدّ الفجوة عند الحدّ بدل تأكيدٍ أعمى (`as`):
 * ما تضمنه القاعدة يمرّ، وأيّ شيءٍ آخر يُعامَل «مجهولاً» (null).
 * ════════════════════════════════════════════════════════════════════
 */

export type Gender = 'male' | 'female';

/** يُضيّق نصّ القاعدة الحرّ إلى المفردات المعتمَدة؛ ما عداها مجهول */
export function toGender(value: string | null | undefined): Gender | null {
  return value === 'male' || value === 'female' ? value : null;
}
