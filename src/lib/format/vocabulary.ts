/**
 * ════════════════════════════════════════════════════════════════════
 * 🔤 تضييق المفردات المحروسة بقيود CHECK
 * ════════════════════════════════════════════════════════════════════
 *
 * أعمدةٌ كثيرة في القاعدة محروسة بقيد CHECK يحصر قيمها في مفرداتٍ مغلقة
 * (`status` · `type` · `tier` · `severity` · `plan` …). لكنّ مولّد أنواع
 * Supabase **لا يقرأ قيود CHECK** — الأنواع المُعدّدة (ENUM) وحدها تُترجم
 * إلى اتّحاد — فيُخرج `string` رغم أنّ القيمة مضمونة من جهة القاعدة.
 *
 * البديل الكسول هو التأكيد الأعمى (`row.status as Status`)، وهو يكذب:
 * يَعِد المُصرِّف بما لا يفحصه أحد. هاتان الدالّتان تفحصان فعلاً عند حدّ
 * الصفحة، فتبقى الأنواع الضيّقة داخل التطبيق **مكسوبةً لا مُدّعاة**.
 *
 * ملاحظة: القيمة الخارجة عن المفردات لا تحدث ما دام القيد قائماً؛ وإن
 * حدثت (قيدٌ أُسقط، بيانات مُدخَلة يدوياً) فالتعامل معها «مجهولاً» أسلم
 * من تمريرها إلى واجهةٍ تفترض غير ذلك.
 * ════════════════════════════════════════════════════════════════════
 */

/** يُضيّق نصّاً حرّاً إلى إحدى المفردات، أو `null` إن لم يُطابق */
export function oneOf<T extends string>(
  allowed: readonly T[],
  value: string | null | undefined
): T | null {
  return value != null && (allowed as readonly string[]).includes(value)
    ? (value as T)
    : null;
}

/**
 * مثلها، لكن بقيمةٍ احتياطية للأعمدة `NOT NULL` المحروسة بـCHECK —
 * حيث القيمة مضمونة والاحتياطي لا يُبلَغ عملياً.
 */
export function oneOfOr<T extends string>(
  allowed: readonly T[],
  value: string | null | undefined,
  fallback: T
): T {
  return oneOf(allowed, value) ?? fallback;
}

/**
 * أعمدة `jsonb` تصل من المولّد بنوع `Json` الواسع (نصّ · رقم · قائمة ·
 * كائن). الواجهات تتوقّع كائناً بشكلٍ معيّن، فيُفحص أنّه كائنٌ فعلاً — لا
 * قائمة ولا قيمة مفردة — قبل تمريره. ما عدا ذلك «مجهول» (null).
 *
 * الشكل الداخلي يبقى غير مفحوص: يكتبه التطبيق نفسه، والفحص العميق هنا
 * يتطلّب مخطّطاً لكل عمود. الغرض منع انهيار قراءة خاصّية من نصّ أو قائمة.
 */
export function jsonObject<T>(value: unknown): T | null {
  return value != null && typeof value === 'object' && !Array.isArray(value)
    ? (value as T)
    : null;
}
