-- قِيس قبله: 14 صفّاً فقط فيها أرقامٌ هنديّة (١٢٣) — عناوينُ الصيدليات (6) والمستشفيات (4)
-- وعياداتُ الأطبّاء (3) واسمُ صيدليّة (1). والكودُ صار يعرض الأرقامَ لاتينيّةً كلَّها
-- (`ar-IQ-u-nu-latn`)، فتبقى هذه وحدها مختلفة.
--
-- بياناتٌ فقط، ويعمل معها كودُ main الحاليّ كما هو. `translate` يحوّل الهنديّة (٠-٩)
-- والفارسيّة (۰-۹) معاً.
