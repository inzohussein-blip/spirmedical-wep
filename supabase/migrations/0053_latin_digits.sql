UPDATE public.pharmacies
   SET address = translate(address, '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', '01234567890123456789'),
       name    = translate(name,    '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', '01234567890123456789')
 WHERE address ~ '[٠-٩۰-۹]' OR name ~ '[٠-٩۰-۹]';

UPDATE public.hospitals
   SET address = translate(address, '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', '01234567890123456789')
 WHERE address ~ '[٠-٩۰-۹]';

UPDATE public.doctors
   SET clinic_address = translate(clinic_address, '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', '01234567890123456789')
 WHERE clinic_address ~ '[٠-٩۰-۹]';
