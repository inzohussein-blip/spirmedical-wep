-- ════════════════════════════════════════════════════════════════════════
-- 0022: إزالة قيد CHECK المتناقض على `users.approval_status`
-- ════════════════════════════════════════════════════════════════════════
--
-- العمود يحمل **قيدَي CHECK معاً**:
--
--   users_approval_status_check → pending · approved · rejected
--   check_approval_status_enum  → pending · approved · rejected · suspended · expired
--
-- وقيود CHECK **تتقاطع ولا تتّحد**: القيمة يجب أن تمرّ من الاثنين. فالمفردات
-- الفعلية هي التقاطع — ثلاث قيم — و`suspended` و`expired` **لا يمكن
-- تخزينهما أبداً** رغم أنّ القيد الأوسع يوحي بأنّهما متاحتان.
--
-- لا أثر عملياً اليوم: الإيقاف مُنفَّذ بعمودٍ منطقيّ منفصل (`is_suspended`
-- و`suspended_at`)، ولا موضع في `src/` يكتب أيّاً من القيمتين — المستعمَل
-- في الكود ثلاث قيمٍ فقط. والقيم المخزَّنة كلّها `approved`.
--
-- لكنّه فخّ لمن يقرأ القيد الأوسع ويظنّ القيمتين متاحتين، فيكتب
-- `approval_status = 'suspended'` ويصطدم بخطأ 23514 من قيدٍ آخر لم يره.
--
-- المُسقَط هو **الأوسع**: إسقاطه لا يغيّر المفردات الفعلية (الأضيق يبقى
-- حارساً)، بينما إسقاط الأضيق كان سيوسّع المسموح — وهو تغيير سلوكٍ لا
-- توضيحٌ له.

ALTER TABLE public.users
  DROP CONSTRAINT IF EXISTS check_approval_status_enum;
