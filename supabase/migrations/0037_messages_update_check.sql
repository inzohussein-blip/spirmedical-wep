-- ════════════════════════════════════════════════════════════════════════
-- 0037: حقنُ رسالةٍ في محادثةٍ خاصّةٍ بين طرفين آخرين
-- ════════════════════════════════════════════════════════════════════════
--
-- سياسةُ الإدراج على `messages` تشترط شرطين معاً:
--
--     sender_id = auth.uid()
--     AND EXISTS (محادثةٌ أنا طرفٌ فيها)
--
-- وسياسةُ التعديل تشترط الأوّل وحده، **وبلا `WITH CHECK` أصلاً**:
--
--     USING (auth.uid() = sender_id)
--
-- فحين لا يُذكر `WITH CHECK` يستعمل Postgres تعبير `USING` مكانه — أي أنّ
-- الصفَّ **الجديد** لا يُفحص إلّا بأنّ مُرسِله هو أنا. و`chat_id` عمودٌ
-- كسائر الأعمدة: يُعدَّل.
--
-- فيكتب المهاجم رسالةً في محادثته هو (مشروع)، ثمّ ينقلها بتعديلٍ إلى أيّ
-- محادثةٍ في المنصّة — بينها محادثاتُ الأطباء بمرضاهم.
--
-- ─── المُثبَت في معاملةٍ مُلغاة ───
--
--     يرى محادثة المريض الخاصّة؟ ....... ٠
--     نقلٌ بشرط `WHERE` ............... مرفوض: new row violates RLS
--     نقلٌ **بلا شرط** ................ نجح! صفوف=١
--     موضع الرسالة أخيراً ............. محادثة المريض الخاصّة
--
-- والفرق بين السطرين هو نفسه الذي كشف ثغرة `appointments` في 0036: التعديل
-- المُرشَّح تحرسه سياسةُ القراءة، وغيرُ المُرشَّح يتخطّاها. ويبلغه المهاجم
-- من PostgREST بطلبٍ واحد: `PATCH /messages` بجسمٍ فيه `chat_id` بلا
-- مُرشِّح.
--
-- الأثر في منصّةٍ طبّية: رسالةٌ مُلفَّقة تظهر داخل محادثةِ طبيبٍ بمريضه.
--
-- ─── الإصلاح ───
--
-- يُضاف `WITH CHECK` صريحٌ يطابق شرطَ الإدراج حرفاً بحرف. فلا يبقى للصفّ
-- الجديد مخرجٌ من الشرط الذي أُدخل به.

DROP POLICY IF EXISTS "Users update own messages" ON public.messages;

CREATE POLICY "Users update own messages" ON public.messages
  FOR UPDATE
  USING (sender_id = (SELECT auth.uid()))
  WITH CHECK (
    sender_id = (SELECT auth.uid())
    AND EXISTS (
      SELECT 1 FROM public.chats c
       WHERE c.id = messages.chat_id
         AND (c.patient_id = (SELECT auth.uid())
           OR c.specialist_id = (SELECT auth.uid()))
    )
  );
