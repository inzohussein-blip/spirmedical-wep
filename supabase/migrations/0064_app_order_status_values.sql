-- 0064: حالتان جديدتان للطلب — «في الطريق» و«وصل»
-- ════════════════════════════════════════════════════════════════════════
--
-- مثل تطبيقات التوصيل: يرى المراجع أنّ المختصّ انطلق، ثمّ أنّه وصل.
--
--   pending → confirmed → on_the_way → arrived → in_progress → completed
--                                                            ↘ cancelled
--
-- في ملفٍّ مستقلّ عمداً: قيمةُ enum المُضافة لا تُستعمل في المعاملة نفسها،
-- ودالّة الانتقال (0065) تستعملها.
--
-- ⚠️ توافقٌ مع الويب: إضافة القيم وحدها لا تغيّر شيئاً حتى يكتبها أحد. لكن
-- قبل أن يبدأ تطبيق «برو» بكتابتها، يجب أن يعرفها الويب: إعادة توليد
-- `types/database.ts` وإضافة عنوانيهما في خرائط الحالات (انظر
-- supabase/migrations/README.md).
-- ════════════════════════════════════════════════════════════════════════

ALTER TYPE public.appointment_status ADD VALUE IF NOT EXISTS 'on_the_way' AFTER 'confirmed';
ALTER TYPE public.appointment_status ADD VALUE IF NOT EXISTS 'arrived' AFTER 'on_the_way';
