-- ════════════════════════════════════════════════════════════════════
-- 0012 — إغلاق تسريب بيانات طبّية عبر منظورَي SECURITY DEFINER
-- ════════════════════════════════════════════════════════════════════
--
-- 🚨 الثغرة:
-- `vitals_trends` و`admin_lab_orders_summary` منظوران يجمعان صفتين خطيرتين:
--   1. `SECURITY DEFINER` (السلوك الافتراضي للمنظورات في Postgres): يُنفَّذان
--      بصلاحيات مالكهما `postgres`، فيتجاوزان RLS على الجداول الأساسية.
--   2. `GRANT SELECT ... TO authenticated`: مُنِحا لكل مستخدمٍ مسجَّل.
--
-- وليس فيهما شرط يقصر النتائج على صاحب البيانات. فأيّ مريض ينشئ حساباً
-- يستطيع — من متصفّحه بمفتاح anon — قراءة:
--   • `vitals_trends`: ضغط الدم والنبض والحرارة والأكسجين وسكّر الدم
--     والملاحظات — لكل مريض في المنصّة.
--   • `admin_lab_orders_summary`: **اسم المريض وهاتفه** مع التحاليل التي
--     طلبها والمختبر والسعر.
--
-- التعليق في الترحيل الأصلي يقول «منح صلاحية القراءة للـadmin»، لكنّ
-- `authenticated` في Supabase تعني **كل** من سجّل الدخول لا الإداريين.
--
-- ✅ الإصلاح: `security_invoker = on` يجعل المنظور يُنفَّذ بصلاحيات
-- **المستعلِم**، فتُطبَّق سياسات RLS على الجداول الأساسية:
--   • المريض يرى صفوفه فقط.
--   • الإداري يرى الجميع (سياسات الأدمن على `nursing_visit_history`
--     و`lab_orders` قائمة أصلاً).
-- أي أنّ الوظيفة المقصودة تبقى، والتسريب يُغلق.
--
-- ملاحظة: لا يستعمل التطبيق أيّاً من المنظورين حالياً، فالتغيير بلا أثر
-- على واجهاتٍ قائمة.
-- ════════════════════════════════════════════════════════════════════

ALTER VIEW public.vitals_trends            SET (security_invoker = on);
ALTER VIEW public.admin_lab_orders_summary SET (security_invoker = on);

-- دفاعٌ في العمق: `anon` لا يحتاج هذين المنظورين إطلاقاً.
REVOKE ALL ON public.vitals_trends            FROM anon;
REVOKE ALL ON public.admin_lab_orders_summary FROM anon;
