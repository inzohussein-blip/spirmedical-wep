--
-- الترحيل 0033 فهرس ٥٦ مفتاحاً أجنبياً غير مفهرس، ثمّ أضفتُ في 0042 جدول
-- `app_settings` بعمود `updated_by` بلا فهرس — فعاد الإنذار من صفرٍ إلى
-- واحد. والعلّة أنّ الحارس لم يكن يشمل هذه العائلة أصلاً.
--
-- وأثرُه هنا صغيرٌ عملياً (الجدولُ صفوفُه قليلة)، لكنّ الفهرس يغطّي ما
-- يفعله Postgres عند حذف مستخدم: يمسح الجدولَ التابعَ كلَّه للتحقّق من
-- `ON DELETE SET NULL`.
--
-- والمصدرُ (0042) صار يُنشئ الفهرسَ بنفسه، فهذا الترحيل لقاعدةٍ قائمةٍ لم
-- يُعَد نشرُها. والحارس `tests/schema-conformance.test.ts` صار يفحص كلَّ
-- مفتاحٍ أجنبيٍّ في الترحيلات: ١٦٣ مفتاحاً، ويطابق عددُه ما تقوله القاعدة
-- الحيّة بالحرف.

CREATE INDEX IF NOT EXISTS idx_app_settings_updated_by
  ON public.app_settings (updated_by)
  WHERE updated_by IS NOT NULL;
